    const rej = await call("POST", `/agent/proposals/${pid}/reject`);
    expect(rej.json).toMatchObject({ status: "rejected", decidedBy: A.owner });
    expect((await call("POST", `/agent/proposals/${pid}/reject`)).status).toBe(409);
