async function call(method: string, path: string, who = A_OWNER, body?: unknown) {
  const res = await fetch(`${baseUrl()}${path}`, {
    method,
    headers: { "content-type": "application/json", "x-test-user": who },
    ...(body !== undefined ? { body: JSON.stringify(body) } : {}),
  });
  const text = await res.text();
  return { status: res.status, headers: res.headers, text, json: text && !text.startsWith(":") && !text.startsWith("event:") ? (JSON.parse(text) as any) : null };
}

function frames(text: string) {
  const out: Array<{ event: string; data: any }> = [];
  for (const block of text.split("\n\n")) {
    if (!block.trim() || block.startsWith(":")) continue;
    const ev = /^event: (.+)$/m.exec(block)?.[1];
    const data = /^data: (.+)$/m.exec(block)?.[1];
    if (ev && data) out.push({ event: ev, data: JSON.parse(data) });
  }
  return out;
}

